bool Map_HasBossTile(int (*map)[MAP_WIDTH])
{
    for (int y = 0; y < MAP_HEIGHT; y++) {
        for (int x = 0; x < MAP_WIDTH; x++) {
            if (map[y][x] == 9) {
                return true;
            }
        }
    }
    return false;
}

bool Map_FindKeyTile(int (*map)[MAP_WIDTH], float *outX, float *outY)
{
    // tile 10 is key
    return Map_FindTile(map, 10, outX, outY);
}

bool Map_IsTileSolid(int (*map)[MAP_WIDTH], int tx, int ty)
{
    if (tx < 0 || ty < 0 || tx >= MAP_WIDTH || ty >= MAP_HEIGHT) return true;
    int t = map[ty][tx];
    return (t == 1);
}

bool Map_FindTile(int (*map)[MAP_WIDTH], int tileValue, float *outX, float *outY)
{
    for (int y = 0; y < MAP_HEIGHT; y++) {
        for (int x = 0; x < MAP_WIDTH; x++) {
            if (map[y][x] == tileValue) {
                *outX = x * TILE_SIZE + TILE_SIZE * 0.5f;
                *outY = y * TILE_SIZE + TILE_SIZE * 0.5f;
                return true;
            }
        }
    }
    return false;
}

int Map_FindAllTiles(int (*map)[MAP_WIDTH], int tileValue, Vector2 *outPositions, int maxOut)
{
    int count = 0;
    for (int y = 0; y < MAP_HEIGHT && count < maxOut; y++) {
        for (int x = 0; x < MAP_WIDTH && count < maxOut; x++) {
            if (map[y][x] == tileValue) {
                float px = x * TILE_SIZE + TILE_SIZE * 0.5f;
                float py = y * TILE_SIZE + TILE_SIZE * 0.5f;
                outPositions[count++] = (Vector2){ px, py };
            }
        }
    }
    return count;
}

bool Map_GetRandomFreeTile(int (*map)[MAP_WIDTH], float *outX, float *outY)
{
    for (int tries = 0; tries < 100; tries++) {
        int tx = GetRandomValue(1, MAP_WIDTH  - 2);
        int ty = GetRandomValue(1, MAP_HEIGHT - 2);
        if (map[ty][tx] != 1) {
            *outX = tx * TILE_SIZE + TILE_SIZE * 0.25f;
            *outY = ty * TILE_SIZE + TILE_SIZE * 0.25f;
            return true;
        }
    }
    return false;
}